        <section>
            <h2>Evaporation & Condensation</h2>
            <p>
                The journey of a single raindrop begins with <strong>evaporation</strong>. Driven by energy from the sun, water transforms from a liquid into an invisible gas called <strong>water vapor</strong>. This gas rises into the atmosphere from oceans, lakes, rivers, soil, and plants—a process in the latter known as <strong>transpiration</strong>.
            </p>
            <p>
                As warm, moist air ascends into the atmosphere, it expands and cools. Cold air holds less moisture than warm air, so as the rising air reaches its <strong>dew point</strong>, the water vapor condenses into liquid water droplets or ice crystals.
            </p><br>
        </section>
        <section>
            <h2>Cloud Formation</h2>
            <p>
                This condensation process requires something to cling to: minute airborne particles known as <strong>cloud condensation nuclei</strong>. These microscopic particles, which include dust, sea salt, pollen, and smoke, act as seeds for cloud droplets. Millions of these tiny droplets cluster together to form visible clouds. Initially, these cloud droplets are extremely small and light—so light that updrafts of air within the cloud keep them floating.
            </p><br>
        </section>
        <section>
            <h2>How Raindrops Grow</h2>
            <p>
                For rain to actually fall, these tiny cloud droplets must grow significantly larger. They accomplish this through two main processes: <strong>collision-coalescence</strong> and <strong>ice crystal growth</strong>.
            </p>
            <p>
                In warmer clouds, larger droplets fall faster than smaller ones, colliding with them and merging to form bigger drops. In colder clouds, where liquid water exists alongside ice crystals below freezing temperatures, water vapor rapidly freezes onto the ice crystals. As these ice crystals grow heavier, they fall toward the ground, often melting into liquid rain as they pass through warmer layers of the lower atmosphere.
            </p><br>
        </section>
        <section>
            <h2>Gravity & Shape</h2>
            <p>
                Once a drop becomes heavy enough to overcome the upward push of air currents, <strong>gravity pulls it downward</strong>. As raindrops fall, air resistance shapes them. Contrary to the popular teardrop icon seen in art, small raindrops are actually <strong>spherical</strong>, while larger falling drops flatten on the bottom like the top half of a hamburger bun.
            </p><br>
        </section>
        <section>
            <h2>Impact on Earth</h2>
            <p>
                When rain hits the ground, it sustains life across the planet. Rain replenishes freshwater reservoirs, nourishes vegetation, prevents forest fires, and washes pollutants from the atmosphere. Beyond its environmental importance, rain carries significant cultural, emotional, and sensory value. The distinctive, earthy smell that accompanies the first rain after a dry spell—known as <strong>petrichor</strong>—is widely cherished. From nourishing crops to driving world weather patterns, rain remains a fundamental force that shapes the physical landscape and fuels the natural rhythm of life on Earth.
            </p><br>
